// To-do generator — a prospective action plan for not-yet-published datasets
// (Plan / Prepare stages). Lists unmet criteria grouped by what is actionable
// now, what is coming up at release, and what must be documented as-is. Emitted
// as Markdown with checkboxes.

import {
  getPathway,
  requiredCriteria,
  recommendedForPathway,
  isCriterionSatisfied,
} from '../lib/pathway.js';
import { isLocked, isUpcoming, getStage } from '../lib/stages.js';
import { validationResults } from '../lib/validation.js';
import { citeThisWorkShort } from '../lib/thisWork.js';

export function generateTodo(record, opts = {}) {
  const { pathway, sub_domain: subDomain, stage, dataset = {}, answers = {} } = record;
  const now = opts.now ?? new Date().toISOString();
  const results = opts.results ?? validationResults(record);
  const meta = getPathway(pathway);
  const stageObj = getStage(stage);

  const unmet = requiredCriteria(pathway, subDomain).filter(
    (c) => !isCriterionSatisfied(c, answers[c.id], results),
  );
  const doNow = unmet.filter((c) => !isLocked(c, stage) && !isUpcoming(c, stage));
  const later = unmet.filter((c) => isUpcoming(c, stage));
  const document = unmet.filter((c) => isLocked(c, stage));
  const optional = recommendedForPathway(pathway).filter(
    (c) => !isCriterionSatisfied(c, answers[c.id], results),
  );

  const lines = [];
  lines.push(`# AI-readiness to-do${dataset.name ? ` — ${dataset.name}` : ''}`);
  lines.push('');
  lines.push(`- **Starting point:** ${stageObj?.title ?? stage ?? '—'}`);
  lines.push(`- **Target pathway:** ${pathway} — ${meta?.name ?? '?'} (${meta?.level ?? '?'})`);
  lines.push(`- **Generated:** ${now}`);
  lines.push('');
  lines.push('> Checklist of what remains to make this dataset AI-ready. Generated by the AI-Readiness Assessment tool.');
  lines.push(`> Implements the framework of ${citeThisWorkShort()}`);
  lines.push('');

  const section = (title, items, note) => {
    if (!items.length) return;
    lines.push(`## ${title}`);
    if (note) lines.push(`_${note}_`);
    lines.push('');
    for (const c of items) {
      lines.push(`- [ ] **${c.label}** _(${c.dimension})_`);
      if (c.remediation) lines.push(`  - ${c.remediation}`);
    }
    lines.push('');
  };

  section('Do now', doNow, 'Actionable at your current stage.');
  section('Coming up — at/before release', later, 'Not due yet; plan for these.');
  section('Document as-is', document, 'Fixed decisions from an earlier stage — record them, or note as known limitations.');
  section('Optional extras (recommended)', optional, 'Not required for this pathway, but strengthen the release.');

  if (!doNow.length && !later.length && !document.length) {
    lines.push('All required criteria for this pathway are already satisfied.');
    lines.push('');
  }

  return lines.join('\n');
}
